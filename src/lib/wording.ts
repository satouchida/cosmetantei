/** AI への指示に足す文（使わない表現を名指しするので、この一覧と同じファイルに置く。test 108 はこのファイルを除く） */
export const PROMPT_WORDING_RULES = `- 効能は化粧品の効能の範囲の言葉（肌を整える・肌をすこやかに保つ・うるおいを与える・肌を保護する等）で書く。「鎮静」「修復」「補修」「抗炎症」「炎症を抑える」は使わない。浸透は「角層まで」と書く
- 「安全に使えます」「安全な成分」「低刺激な成分」のように安全を言い切らない。パッチテストは勧めず、試すときは「腕の内側など目立たない部分で試す」と書く
- 「有効成分」は医薬部外品の承認の説明にだけ使う。「シミを消す」「ニキビを治す」「シワを改善」「若返り」のように、化粧品の効能の範囲を超える効果は書かない
- 肌の手当ての方法（「肌を休ませる」「〜だけを使う」等）は書かない。症状があるときは「使用を中止し、皮膚科専門医に相談する」とだけ書く`;

export const PROHIBITED_CLAIMS = new RegExp(PROHIBITED.join('|'));

/**
 * 返答に使えない言い切り（安全・効果を保証する、治ると言う）。指示を書き換えられた返答や、指示に従わない返答を、
 * 利用者に見せない（このアプリは原因になりうる成分の候補を示すだけで、診断・保証はしない）
 */
const ASSURANCE_PATTERN = /必ず安全|絶対(?:に)?安全|100\s*[%％]\s*安全|安全(?:です|を)保証|治ります|治せます|完治|治療でき|副作用はありません|誰でも安心/g;
/** 言い切りの直後に否定が続く文（「必ず安全とは限りません」「完治しません」）は、言い切りではない */
const NEGATED_AFTER = /^[^。！!\n]{0,10}(?:ません|ない|限らない|できない)/;
/** 「副作用はありません」は否定の形の言い切りなので、否定が続いても言い切りとして扱う */
const ALWAYS_ASSURANCE = /^副作用はありません$/;

export function hasAssurance(text: string): boolean {
  for (const m of text.matchAll(ASSURANCE_PATTERN)) {
    if (ALWAYS_ASSURANCE.test(m[0]) || !NEGATED_AFTER.test(text.slice((m.index ?? 0) + m[0].length))) return true;
  }
  return false;
}

/** AI が書いた文に、使わない表現か保証の言い切りがあるか（チャットの返答・成分の解説で同じ基準） */
export function hasProhibitedClaim(text: string): boolean {
  return PROHIBITED_CLAIMS.test(text) || hasAssurance(text);
}

/**
 * 「肌を整える・うるおいを保つ成分」の緑の枠に出す解説から、安全性評価の結論の文（「…化粧品での使用を安全としています」）を除く。
 * 緑の枠の中では安全のお墨付きに読める（成分の詳しい解説には残す）
 */
const SAFETY_VERDICT = /安全(?:と(?:し|評価|され|判断|認め)|性が確認)/;

export function withoutSafetyRating(reasonJa: string): string {
  const kept = (reasonJa.match(/[^。！？\n]+[。！？]?/g) ?? []).filter((s) => !SAFETY_VERDICT.test(s));
  return kept.length > 0 ? kept.join('') : reasonJa;
}
