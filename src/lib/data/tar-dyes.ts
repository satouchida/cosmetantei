/**
 * 色素の名前の形（成分DB・表示指定成分の照合で同じものを使う）
 * - タール色素：医薬品等に使用することができるタール色素を定める省令（昭和41年厚生省令第30号）別表の83品目。
 *   名前はどれも「赤色202号」の形で、表示では「赤202」とも書く（「赤色104号の(1)」「Ext.紫201号」「黄4アルミニウムレーキ」も）。
 *   省令の名前は「だいだい色」「褐色」、表示では「橙」「かっ色」とも書く
 * - CI 番号：Colour Index の番号（「CI 15850」「C.I. 15850:1」）。日本化粧品工業会の表にある番号はそのタール色素に。
 *   ほかは番号の帯で色素の種類が決まる
 *   （Colour Index「CICN Groups & Sub-groups」：10000〜74999 は合成の有機色素、うち 11000〜39999 はアゾ色素、
 *   40800〜40999 はカロテノイド、75000〜75999 は天然の色素、77000〜77999 は無機顔料）
 */

/**
 * 省令の別表の83品目（色ごとの番号。「の(1)」「の(2)」のある品目は枝番も）。e-Gov の別表（2019年7月1日施行の版）から。
 * 第一部：赤2・3・102・104の(1)・105の(1)・106、黄4・5、緑3、青1・2。第二部：200番台。第三部：400番台・500番台
 */
const TAR_DYES: Record<string, Record<number, number[]>> = {
  赤: {
    2: [], 3: [], 102: [], 104: [1], 105: [1], 106: [],
    201: [], 202: [], 203: [], 204: [], 205: [], 206: [], 207: [], 208: [], 213: [], 214: [], 215: [], 218: [], 219: [],
    220: [], 221: [], 223: [], 225: [], 226: [], 227: [], 228: [], 230: [1, 2], 231: [], 232: [],
    401: [], 404: [], 405: [], 501: [], 502: [], 503: [], 504: [], 505: [], 506: [],
  },
  橙: { 201: [], 203: [], 204: [], 205: [], 206: [], 207: [], 401: [], 402: [], 403: [] },
  黄: { 4: [], 5: [], 201: [], 202: [1, 2], 203: [], 204: [], 205: [], 401: [], 402: [], 403: [1], 404: [], 405: [], 406: [], 407: [] },
  緑: { 3: [], 201: [], 202: [], 204: [], 205: [], 401: [], 402: [] },
  青: { 1: [], 2: [], 201: [], 202: [], 203: [], 204: [], 205: [], 403: [], 404: [] },
  褐: { 201: [] },
  紫: { 201: [], 401: [] },
  黒: { 401: [] },
};

/**
 * タール色素の名前の形（normalizeIngredientName の後の形。括弧・空白・中黒は外れている）。
 * 番号が別表にあるかは tarDyeOf で確かめる（この形だけでは「赤40」「赤2021」も合う）
 */
export const TAR_DYE_NAME = /^(?:ext\.?)?(赤|黄|青|緑|橙|だいだい|褐|かっ|紫|黒)色?(\d{1,3})号?(?:の?([12]))?(?:.*レーキ)?$/;

/**
 * タール色素の色と番号（「赤色219号」→ { color: '赤', number: 219 }）。別表に無い番号・枝番の無い品目の枝番
 * （「赤2021」）は null
 */
export function tarDyeOf(normalizedName: string): { color: string; number: number } | null {
  const m = TAR_DYE_NAME.exec(normalizedName);
  if (!m) return null;
  const color = m[1] === 'だいだい' ? '橙' : m[1] === 'かっ' ? '褐' : m[1];
  const number = Number(m[2]);
  const branches = TAR_DYES[color]?.[number];
  if (!branches || (m[3] && !branches.includes(Number(m[3])))) return null;
  return { color, number };
}

/** 別表の品目の数（テスト用） */
export const TAR_DYE_COUNT = Object.values(TAR_DYES).reduce(
  (n, byNumber) => n + Object.values(byNumber).reduce((k, branches) => k + Math.max(1, branches.length), 0),
  0
);

/** CI 番号の表示（normalizeIngredientName の後の形：「ci15850」「c.i.15850:1」）。5桁の番号と、塩の違いのコロンの後の番号 */
const CI_NUMBER = /^c\.?i\.?(\d{5})(?::(\d+))?$/;

/**
 * CI 番号とタール色素の対応。日本化粧品工業会「The List of JCIA Standards for Tar Colors」(2024年3月19日) の表に
 * 載っている38品目だけ（「CI 15850」は赤201、「CI 15850:1」は赤202。塩が違えばコロンの後の番号が違う）。
 * 表に無い番号（CI 47000 等）は、ほかの資料で同じ色素と分かっても対応させない
 */
const CI_TAR_DYES: Record<string, [string, number]> = {
  // 自主基準で管理値のある色素（同 p.2）
  '15850': ['赤', 201], '15850:1': ['赤', 202], '15585': ['赤', 203], '15585:1': ['赤', 204], '15800:1': ['赤', 219],
  '15880:1': ['赤', 220], '12120': ['赤', 221], '26100': ['赤', 225], '17200': ['赤', 227], '12085': ['赤', 228],
  '45190': ['赤', 401], '15865': ['赤', 405], '14700': ['赤', 504], '20170': ['褐', 201], '15510': ['橙', 205],
  '15985': ['黄', 5], '21090': ['黄', 205], '20470': ['黒', 401],
  // 使用を自粛している色素（同 p.1）
  '42095': ['緑', 205], '45170': ['赤', 214], '16155': ['赤', 502], '16150': ['赤', 503], '12140': ['赤', 505],
  '15620': ['赤', 506], '14600': ['橙', 402], '45350': ['黄', 202], '11380': ['黄', 404], '11390': ['黄', 405],
  '18820': ['黄', 407], '42085': ['緑', 402], '26105': ['赤', 501], '21110': ['橙', 204], '12100': ['橙', 403],
  '15630': ['赤', 205], '15630:2': ['赤', 206], '15630:1': ['赤', 207], '15630:3': ['赤', 208], '12315': ['赤', 404],
};

/** CI 番号で書かれたタール色素（「CI 15800:1」→ { color: '赤', number: 219 }）。表に無い番号は null */
export function tarDyeOfCi(normalizedName: string): { color: string; number: number } | null {
  const m = CI_NUMBER.exec(normalizedName);
  const hit = m && CI_TAR_DYES[m[2] ? `${m[1]}:${m[2]}` : m[1]];
  return hit ? { color: hit[0], number: hit[1] } : null;
}

/** CI 番号の対応表の品目の数（テスト用） */
export const CI_TAR_DYE_COUNT = Object.keys(CI_TAR_DYES).length;

/**
 * 合成の有機色素の CI 番号か（10000〜74999。カロテノイド 40800〜40999 は除く）。
 * 天然の色素（カルミン等）・無機顔料（酸化鉄・酸化チタン等）・6桁の番号は当てない
 */
export function isSyntheticOrganicCiNumber(normalizedName: string): boolean {
  const m = CI_NUMBER.exec(normalizedName);
  if (!m) return false;
  const n = Number(m[1]);
  return n >= 10000 && n <= 74999 && !(n >= 40800 && n <= 40999);
}
