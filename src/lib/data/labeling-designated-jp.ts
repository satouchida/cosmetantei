/**
 * 表示指定成分：名称を記載しなければならない医薬部外品の成分（平成12年厚生省告示第332号の
 * 「人体に直接使用されるもの」、平成21年厚生労働省告示第29号による改正後）。140 項目。
 *
 * - 医薬発第990号（平成12年9月29日）によると、医薬部外品の表示対象成分は「消費者が医師からの情報をもとに
 *   アレルギー等の皮膚障害を起こすおそれのある製品の使用を自ら避けることを目的として」指定され、
 *   告示第332号で指定した成分は「従前指定している成分と同様のもの」。化粧品にも同じ目的の指定（102種類。
 *   昭和55年厚生省告示第167号）があったが、2001年4月の全成分表示に替わって廃止された（いわゆる旧表示指定成分）。
 *   昭和55年の告示そのものの成分リストは公的な掲載が見つからないため、ここでは現行の告示第332号を使う
 * - 成分の一覧と、表示に使える別名（Ⅱ〜Ⅳ欄）は、神奈川県「表示・添付文書等チェックリスト（医薬部外品）」の
 *   参考資料①②（告示第332号の本文と、薬食発第0307001号「名称を記載しなければならない医薬部外品の成分の
 *   別名等について」の別表）から写した。告示・通知は著作権の対象外（著作権法13条）。
 *   別名の表に無い名前（INCI 名・化粧品の表示名称）は、同じ物質と確かなものだけを足した
 * - 手順と照合の記録: docs/plans/japan-ingredient-data.md の Step 6
 *
 * - names: 成分表示と照合する名前。designatedKey でそろえて完全一致で照合する
 * - quasiDrugNames: 医薬部外品の表示でだけ、この成分を指す名前。化粧品の表示名称では、より広い物質を指す
 *   （化粧品の「トコフェロール」は天然の d-α 体も含むが、告示は dl-α 体だけ）
 * - namePattern: 「及びその塩類」などの物質群（designatedKey でそろえた名前に対して）
 */

