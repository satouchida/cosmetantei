export interface DesignatedEntry {
  /** 告示の番号（平成21年の改正後） */
  no: number;
  /** 告示の成分名（漢数字の位置番号はアラビア数字に） */
  nameJa: string;
  names: string[];
  quasiDrugNames?: string[];
  namePattern?: RegExp;
}

/** 塩の部分（designatedKey・abbreviateIngredientName でそろえた形。ナトリウム→na など） */
const SALT =
  '(塩|na|2na|3na|4na|k|2k|ca|mg|al|zn|ti|アンモニウム|mea|dea|tea|モノエタノールアミン|ジエタノールアミン|トリエタノールアミン)';
const salts = (base: string) => new RegExp(`^${base}${SALT}(液|末)?$`);
const andSalts = (base: string) => new RegExp(`^${base}(${SALT}(液|末)?)?$`);

const e = (no: number, nameJa: string, names: string[] = [], namePattern?: RegExp): DesignatedEntry => ({
  no,
  nameJa,
  names: [nameJa, ...names],
  ...(namePattern && { namePattern }),
});
const withQuasiDrugNames = (entry: DesignatedEntry, quasiDrugNames: string[]): DesignatedEntry => ({ ...entry, quasiDrugNames });

